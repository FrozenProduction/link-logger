# --- Routes ---


@app.get("/api/limits", response_model=LimitsResponse)
def limits():
    return LimitsResponse(links_per_owner=MAX_LINKS_PER_OWNER, ttl_days=LINK_TTL_DAYS)


@app.post("/api/links", response_model=LinkCreatedResponse, status_code=201)
def create_link(request: Request, payload: LinkCreateRequest, owner: OwnerDep):
    purge_expired(owner)

    if payload.custom_code:
        short_code = payload.custom_code
        existing = store.execute(
            "SELECT id FROM links WHERE short_code = ?", (short_code,)
        )[0]
        if existing:
            raise HTTPException(status_code=400, detail="Custom code already exists")
    else:
        short_code = generate_short_code(6)
        while store.execute("SELECT id FROM links WHERE short_code = ?", (short_code,))[0]:
            short_code = generate_short_code(6)

    now = utc_now()
    created_at = utc_iso(now)
    expires_at = utc_iso(now + timedelta(days=LINK_TTL_DAYS))
    try:
        inserted = store.execute(
            "INSERT INTO links (original_url, short_code, created_at, expires_at, owner_token, clicks) "
            "VALUES (?, ?, ?, ?, ?, 0) RETURNING id",
            (str(payload.original_url), short_code, created_at, expires_at, owner),
        )[0]
    except (sqlite3.IntegrityError, StoreError) as exc:
        # Lost a race on UNIQUE(short_code): a custom code taken between the
        # check and the insert, or a random collision. A network failure is not
        # the client's fault and must not be reported as a duplicate code.
        if is_unique_violation(exc):
            raise HTTPException(status_code=400, detail="Custom code already exists")
        raise

    evicted_code, evicted_count = evict_overflow(owner)
    base_url = public_base_url(request)
    return LinkCreatedResponse(
        id=inserted[0]["id"],
        original_url=str(payload.original_url),
        short_code=short_code,
        short_url=build_short_url(base_url, short_code),
        created_at=created_at,
        expires_at=expires_at,
        clicks=0,
        evicted_code=evicted_code if evicted_count else None,
    )


@app.get("/api/links", response_model=list[LinkResponse])
def list_links(request: Request, owner: OwnerDep):
    rows = store.execute(
        "SELECT id, original_url, short_code, created_at, expires_at, clicks FROM links "
        "WHERE owner_token = ? AND expires_at > ? ORDER BY created_at DESC, id DESC",
        (owner, utc_iso(utc_now())),
    )[0]
    base_url = public_base_url(request)
    return [row_to_response(row, base_url) for row in rows]


@app.get("/api/links/{link_id}", response_model=LinkDetailResponse)
def get_link(request: Request, link_id: int, owner: OwnerDep):
    found = store.execute(
        "SELECT id, original_url, short_code, created_at, expires_at, clicks FROM links "
        "WHERE id = ? AND owner_token = ? AND expires_at > ?",
        (link_id, owner, utc_iso(utc_now())),
    )[0]
    if not found:
        raise HTTPException(status_code=404, detail="Link not found")
    link = found[0]

    # Clicks per day
    clicks = store.execute(
        """
        SELECT DATE(clicked_at) as day, COUNT(*) as count
        FROM clicks
        WHERE link_id = ?
        GROUP BY day
        ORDER BY day
        """,
        (link_id,),
    )[0]
    clicks_breakdown = {row["day"]: row["count"] for row in clicks}

    base_url = public_base_url(request)
    return LinkDetailResponse(
        **row_to_response(link, base_url).model_dump(),
        clicks_breakdown=clicks_breakdown,
    )


@app.get("/{code}")
def redirect_to_original(code: str, request: Request):
    found = store.execute(
        "SELECT id, original_url, expires_at FROM links WHERE short_code = ?", (code,)
    )[0]
    if not found:
        raise HTTPException(status_code=404, detail="Link not found")
    link = found[0]

    if link["expires_at"] <= utc_iso(utc_now()):
        # 410 is the honest status: the resource existed and is deliberately
        # gone, which is exactly what a retention policy does.
        return HTMLResponse(
            content=EXPIRED_PAGE.replace("__FRONTEND__", FRONTEND_URL), status_code=410
        )

    # Record click
    store.execute(
        "INSERT INTO clicks (link_id, clicked_at, ip_address, user_agent) VALUES (?, ?, ?, ?)",
        (
            link["id"],
            utc_iso(utc_now()),
            anonymize_ip(request.client.host) if request.client else "unknown",
            request.headers.get("user-agent", "unknown"),
        ),
    )
    store.execute("UPDATE links SET clicks = clicks + 1 WHERE id = ?", (link["id"],))

    return RedirectResponse(url=link["original_url"], status_code=302)


@app.delete("/api/links/{link_id}", status_code=204)
def delete_link(link_id: int, owner: OwnerDep):
    # Scoped to the owner: an id is guessable, a token is not.
    found = store.execute(
        "SELECT id FROM links WHERE id = ? AND owner_token = ?", (link_id, owner)
    )[0]
    if not found:
        raise HTTPException(status_code=404, detail="Link not found")
    delete_links([link_id])


@app.get("/api/health")
def health_check():
    try:
        total = store.execute("SELECT COUNT(*) AS count FROM links")[0][0]["count"]
    except StoreError as exc:
        return JSONResponse(
            status_code=503,
            content={"status": "degraded", "store": store.name, "detail": str(exc)},
        )
    return {"status": "ok", "store": store.name, "links": total}
