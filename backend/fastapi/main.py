@asynccontextmanager
async def lifespan(app: FastAPI):
    init_db(store)
    yield


app = FastAPI(
    title="Link Logger API",
    description="URL shortener with click analytics and per-browser link slots",
    version="1.2.0",
    lifespan=lifespan,
)

# CORS — allows the Vercel frontend to access the API
app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        "https://link-logger-pink.vercel.app",
        "http://localhost:5173",
        "http://127.0.0.1:5173",
        "http://localhost:8000",
    ],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# --- Product limits ---
# A browser keeps MAX_LINKS_PER_OWNER live links; creating one more evicts the
# oldest. Links also expire TTL_DAYS after creation, so an abandoned database
# cannot grow forever, and no cron job is needed on a free tier.
MAX_LINKS_PER_OWNER = int(os.environ.get("MAX_LINKS_PER_OWNER", "10"))
LINK_TTL_DAYS = int(os.environ.get("LINK_TTL_DAYS", "30"))
# The expired page is served by the API host, so its link back must point at
# the app, not at "/" (which on the API host is a 404).
FRONTEND_URL = os.environ.get("FRONTEND_URL", "https://link-logger-pink.vercel.app").rstrip("/")
if not FRONTEND_URL.startswith(("http://", "https://")):
    FRONTEND_URL = "https://link-logger-pink.vercel.app"

# The token is generated by the browser and is not a secret: it scopes a list,
# it does not authorise access beyond that browser's own demo links. Validated
# anyway so junk cannot poison the column or the index.
OWNER_TOKEN_RE = re.compile(r"^[A-Za-z0-9_-]{8,64}$")


def utc_now() -> datetime:
    return datetime.now(timezone.utc)


def utc_iso(moment: datetime) -> str:
    """Fixed-width UTC ISO-8601. The fixed width is what makes the SQL string
    comparisons (`expires_at > ?`) exact — no locale, no missing microseconds."""
    return moment.strftime("%Y-%m-%dT%H:%M:%S.%f+00:00")


def get_base_url_from_env() -> str:
    """Get the publicly reachable base URL from environment, if set."""
    return os.environ.get("BASE_URL", "").rstrip("/")


# --- Schemas ---


class LinkCreateRequest(BaseModel):
    original_url: AnyUrl
    custom_code: Optional[str] = None

    @field_validator("original_url")
    @classmethod
    def http_schemes_only(cls, v):
        # AnyUrl accepts javascript:, data:, file: and ftp:. A shortener that
        # redirects to those is an open redirect and, once the UI renders the
        # destination as a link, stored XSS. Only http(s) can be shortened.
        if v.scheme not in ("http", "https"):
            raise ValueError("only http and https URLs can be shortened")
        return v

    @field_validator("custom_code")
    @classmethod
    def validate_custom_code(cls, v):
        if v and (len(v) < 3 or len(v) > 20):
            raise ValueError("custom_code must be 3-20 characters")
        if v and not all(c.isalnum() or c in "-_" for c in v):
            raise ValueError("custom_code can only contain letters, numbers, - and _")
        return v


class LinkResponse(BaseModel):
    id: int
    original_url: str
    short_code: str
    short_url: str
    created_at: str
    expires_at: str
    clicks: int

    model_config = {"from_attributes": True}


class LinkCreatedResponse(LinkResponse):
    # Set when the new link pushed the owner over the cap; the UI names the
    # link it replaced instead of letting it vanish silently.
    evicted_code: Optional[str] = None


class LinkDetailResponse(LinkResponse):
    clicks_breakdown: Optional[dict] = None


class LimitsResponse(BaseModel):
    links_per_owner: int
    ttl_days: int


# --- Owner scope ---


def owner_token(x_owner_token: Annotated[Optional[str], Header(alias="X-Owner-Token")] = None) -> str:
    if not x_owner_token or not OWNER_TOKEN_RE.fullmatch(x_owner_token):
        raise HTTPException(
            status_code=400,
            detail="X-Owner-Token header is required (8-64 characters: letters, numbers, - or _)",
        )
    return x_owner_token


OwnerDep = Annotated[str, Depends(owner_token)]


# --- Helpers ---


def generate_short_code(length: int = 6) -> str:
    chars = string.ascii_letters + string.digits
    return "".join(secrets.choice(chars) for _ in range(length))


def anonymize_ip(ip: str) -> str:
    """One-way hash of visitor IPs — analytics counts stay accurate
    without storing raw addresses alongside click history."""
    return hashlib.sha256(ip.encode("utf-8")).hexdigest()[:32]


def build_short_url(base_url: str, short_code: str) -> str:
    """Build a public short URL from base_url + short_code."""
    return f"{base_url.rstrip('/')}/{short_code}"


def public_base_url(request: Request) -> str:
    return get_base_url_from_env() or str(request.url).rsplit("/api", 1)[0]


def is_unique_violation(exc: Exception) -> bool:
    if isinstance(exc, sqlite3.IntegrityError):
        return True
    message = str(exc).upper()
    return "UNIQUE CONSTRAINT" in message or "SQLITE_CONSTRAINT" in message


def delete_links(ids: list[int]) -> None:
    marks = ",".join("?" * len(ids))
    store.execute(f"DELETE FROM clicks WHERE link_id IN ({marks})", tuple(ids))
    store.execute(f"DELETE FROM links WHERE id IN ({marks})", tuple(ids))


def purge_expired(owner: str) -> None:
    """Expired links stop counting against the cap the moment they expire, and
    are physically removed here instead of by a cron job (free tiers have none)."""
    expired = store.execute(
        "SELECT id FROM links WHERE owner_token = ? AND expires_at <= ?",
        (owner, utc_iso(utc_now())),
    )[0]
    if expired:
        delete_links([row["id"] for row in expired])


def evict_overflow(owner: str) -> tuple[Optional[str], int]:
    """Delete this owner's links beyond the cap. Returns (oldest evicted code,
    count evicted)."""
    rows = store.execute(
        "SELECT id, short_code FROM links WHERE owner_token = ? ORDER BY created_at DESC, id DESC",
        (owner,),
    )[0]
    extra = rows[MAX_LINKS_PER_OWNER:]
    if not extra:
        return None, 0
    delete_links([row["id"] for row in extra])
    return extra[-1]["short_code"], len(extra)


def row_to_response(row: dict, base_url: str) -> LinkResponse:
    return LinkResponse(
        id=row["id"],
        original_url=row["original_url"],
        short_code=row["short_code"],
        short_url=build_short_url(base_url, row["short_code"]),
        created_at=row["created_at"],
        expires_at=row["expires_at"],
        clicks=row["clicks"],
    )


